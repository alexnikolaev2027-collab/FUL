        fn = getattr(page, "close_drawer", None)
        if fn is not None:
            try:
                result = fn()
                if hasattr(result, "__await__"):
                    await result
                page.update()
                return
            except Exception:
                pass
        try:
            drawer.open = False
            page.update()
        except Exception:
            pass

